from app.services.investigation_service import investigation_service
from app.repositories.investigation_repository import investigation_repo
from datetime import datetime

class ExportService:
    def export_markdown(self, investigation_id: str) -> str:
        data = investigation_service.get_unified_timeline(investigation_id)
        inv = investigation_repo.get_by_id(investigation_id)
        events = investigation_repo.get_events(investigation_id)
        
        if not inv:
            return "# Investigation Not Found"

        md = f"# Investigation Report: {inv['title']}\n\n"
        
        md += "## Case Information\n\n"
        md += f"| Field | Value |\n"
        md += f"| :--- | :--- |\n"
        md += f"| **Investigation ID** | `{inv['id']}` |\n"
        md += f"| **Status** | {inv['status']} |\n"
        md += f"| **Severity** | {inv['severity']} |\n"
        md += f"| **Created At** | {inv['created_at']} |\n"
        md += f"| **Last Updated** | {inv['updated_at']} |\n\n"

        md += "---\n\n"
        md += "## Investigation Narrative\n\n"
        
        for entry in data:
            ts = datetime.fromisoformat(entry['timestamp'].replace('Z', '+00:00')).strftime('%Y-%m-%d %H:%M:%S')
            md += f"### {ts} — {entry['title']}\n"
            md += f"{entry['description']}\n\n"
            if entry.get('event_summary'):
                md += f"> **Evidence Detail**: {entry['event_summary']}\n\n"

        md += "---\n\n"
        md += "## Evidence Inventory\n\n"
        md += "| Timestamp | Severity | Type | Source | Source IP |\n"
        md += "| :--- | :--- | :--- | :--- | :--- |\n"
        for ev in events:
            md += f"| {ev['timestamp']} | {ev['severity']} | {ev['event_type']} | {ev['source']} | {ev['source_ip']} |\n"

        md += "\n\n---\n"
        md += f"*Generated by MediShield SOC Engine on {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}*"
        
        return md

    def export_json(self, investigation_id: str) -> dict:
        inv = investigation_repo.get_by_id(investigation_id)
        events = investigation_repo.get_events(investigation_id)
        timeline = investigation_service.get_unified_timeline(investigation_id)
        
        return {
            "metadata": inv,
            "timeline": timeline,
            "evidence": events,
            "exported_at": datetime.now().isoformat()
        }

export_service = ExportService()
